#!/usr/bin/env python3
import os
import sys
import argparse
import numpy as np
import xarray as xr

def main():
    parser = argparse.ArgumentParser(description="Generate climatology and empirical terciles for CORE variables.")
    parser.add_argument("var_key", type=str, help="Variable key (e.g. HGT500, TMP850, UGRD200)")
    parser.add_argument(
    "--base-dir",
    type=str,
    default="SFS_VERIF_DATA/verifying_truths/CORE",
    help="Base CORE verification directory"
    )
    args = parser.parse_args()

    var_key = args.var_key
    var_lower = var_key.lower()

    m_dir = os.path.join(args.base_dir, f"{var_key}", "monthly")
    c_dir = os.path.join(args.base_dir, f"{var_key}", "climatology")
    os.makedirs(c_dir, exist_ok=True)

    print(f"Processing climatology for CORE_{var_key}...")
    print(f"Input Directory:  {m_dir}")
    print(f"Output Directory: {c_dir}")

    for mm in range(1, 13):
        mm_str = f"{mm:02d}"
        files = [
            f"{m_dir}/core_{var_lower}_{yyyy}{mm_str}.nc"
            for yyyy in range(1991, 2021)
            if os.path.exists(f"{m_dir}/core_{var_lower}_{yyyy}{mm_str}.nc")
        ]

        if not files:
            print(f"No files found for month {mm_str} in {m_dir}. Skipping.")
            continue

        # Open datasets directly
        ds_list = [xr.open_dataset(f) for f in files]
        
        # Concatenate along time dimension across 1991-2020 base period
        ds_combined = xr.concat(ds_list, dim="time")

        # 1. Compute Mean Climatology
        ds_mean = ds_combined.mean(dim="time", keep_attrs=True)
        ds_std = ds_combined.std(dim="time", keep_attrs=True)

        # 2. Compute Empirical Terciles
        ds_p33 = ds_combined.quantile(1/3, dim="time", keep_attrs=True).drop_vars("quantile", errors="ignore")
        ds_p67 = ds_combined.quantile(2/3, dim="time", keep_attrs=True).drop_vars("quantile", errors="ignore")

        # 3. Assemble unified output dataset for EVS/METplus
        out_ds = xr.Dataset()

        for var in ds_combined.data_vars:
            orig_long_name = ds_combined[var].attrs.get("long_name", var)

            # Keep main variable name generated by wgrib2 (e.g. TMP_850mb) with _mean suffix
            out_ds[f"{var}_mean"] = ds_mean[var].astype(np.float32)
            out_ds[f"{var}_mean"].attrs["long_name"] = f"{orig_long_name} (1991-2020 Mean)"

            out_ds[f"{var}_std"] = ds_std[var].astype(np.float32)
            out_ds[f"{var}_std"].attrs["long_name"] = f"{orig_long_name} (1991-2020 Std Dev)"

            # Tercile bounds
            out_ds[f"{var}_p33"] = ds_p33[var].astype(np.float32)
            out_ds[f"{var}_p33"].attrs["long_name"] = f"{orig_long_name} (1991-2020 33.3rd Empirical Percentile)"

            out_ds[f"{var}_p67"] = ds_p67[var].astype(np.float32)
            out_ds[f"{var}_p67"].attrs["long_name"] = f"{orig_long_name} (1991-2020 66.7th Empirical Percentile)"

        # 4. Clear encodings to prevent unlimited_dims warnings
        out_ds.encoding = {}
        for var in out_ds.data_vars:
            out_ds[var].encoding = {}

        # Save climatology NetCDF file
        out_file = f"{c_dir}/core_{var_lower}_clim_{mm_str}.nc"
        out_ds.to_netcdf(out_file)

        # Clean up open file handles
        for ds in ds_list:
            ds.close()

        print(f"Saved: {out_file}")

if __name__ == "__main__":
    main()
